import AppKit
import Foundation
import Testing
import FluxCore
@testable import FluxPlatform

@MainActor @Test(.timeLimit(.minutes(1)))
func clipboardSecretTypesAndHTMLNeverBecomeHistoryContent() async throws {
    let name = "org.fluxfixture.clipboard." + UUID().uuidString
    let pasteboard = NSPasteboard(name: .init(name))
    defer { pasteboard.releaseGlobally() }
    let channel = PasteboardChannel(name: name)
    for marker in ["org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"] {
        let item = NSPasteboardItem()
        item.setString("PRIVATE CANARY", forType: .string)
        item.setData(Data(), forType: .init(marker))
        pasteboard.clearContents()
        #expect(pasteboard.writeObjects([item]))
        let sample = await channel.capture(expectedChange: pasteboard.changeCount)
        #expect(sample == nil)
    }
    pasteboard.clearContents()
    pasteboard.setData(Data("<img src='https://example.invalid/DO-NOT-FETCH'>".utf8), forType: .html)
    let sample = await channel.capture(expectedChange: pasteboard.changeCount)
    #expect(sample?.payload == .unsupported)
}

@MainActor @Test(.timeLimit(.minutes(1)))
func clipboardRoundTripsTextAndMultipleFileURLsWithoutSplittingNames() async throws {
    let name = "org.fluxfixture.clipboard." + UUID().uuidString
    let pasteboard = NSPasteboard(name: .init(name))
    defer { pasteboard.releaseGlobally() }
    let channel = PasteboardChannel(name: name)
    let text = "  A line\nwith a trailing newline\n"
    let first = try #require(await channel.write(.text(text, .text)))
    #expect(pasteboard.string(forType: .string) == text)
    #expect(await channel.capture(expectedChange: first)?.payload == .text(text, .text))
    let files = [URL(fileURLWithPath: "/tmp/file\nname"), URL(fileURLWithPath: "/tmp/another file")]
    let second = try #require(await channel.write(.files(files)))
    #expect(await channel.capture(expectedChange: second)?.payload == .files(files))
    #expect(await channel.capture(expectedChange: first) == nil)
    let previous = pasteboard.changeCount
    #expect(await channel.write(.unsupported) == nil)
    #expect(pasteboard.changeCount == previous)
}
