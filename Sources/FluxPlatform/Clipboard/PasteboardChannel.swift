import AppKit
import Foundation
import ImageIO
import FluxCore

public struct ClipboardSample: Equatable, Sendable {
    public let changeCount: Int
    public let capturedAt: Date
    public let payload: ClipboardPayload
}

public protocol ClipboardChannel: Sendable {
    func changeCount() async -> Int
    func capture(expectedChange: Int) async -> ClipboardSample?
    func write(_ payload: ClipboardPayload) async -> Int?
}

/// Clipboard IPC, rich-text parsing and image work stay on this actor.
/// Construction does not touch the pasteboard. It never imports HTML.
public actor PasteboardChannel: ClipboardChannel {
    private let name: String?
    private var pasteboard: NSPasteboard?
    private static let privateTypes = Set([
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType", "org.nspasteboard.AutoGeneratedType"
    ])

    public init(name: String? = nil) { self.name = name }

    public func changeCount() -> Int { board().changeCount }

    public func capture(expectedChange: Int) -> ClipboardSample? {
        let pasteboard = board()
        guard pasteboard.changeCount == expectedChange,
              let items = pasteboard.pasteboardItems, !items.isEmpty, items.count <= 1000,
              !items.contains(where: { item in item.types.contains { Self.privateTypes.contains($0.rawValue) } }) else { return nil }
        let payload: ClipboardPayload
        let urls = items.compactMap { $0.string(forType: .fileURL) }.compactMap(URL.init(string:)).filter(\.isFileURL)
        if !urls.isEmpty {
            payload = .files(urls)
        } else if let bytes = pasteboard.data(forType: .png) ?? pasteboard.data(forType: .tiff) {
            payload = Self.image(bytes)
        } else if let string = Self.plainText(pasteboard), !string.isEmpty {
            payload = .text(string, ClipboardHistory.classify(string))
        } else {
            payload = .unsupported
        }
        guard pasteboard.changeCount == expectedChange else { return nil }
        return .init(changeCount: expectedChange, capturedAt: .now, payload: payload)
    }

    public func write(_ payload: ClipboardPayload) -> Int? {
        let items: [NSPasteboardItem]
        switch payload {
        case .text(let string, _):
            let item = NSPasteboardItem()
            guard item.setString(string, forType: .string) else { return nil }
            items = [item]
        case .files(let urls):
            guard !urls.isEmpty, urls.allSatisfy(\.isFileURL) else { return nil }
            items = urls.map {
                let item = NSPasteboardItem()
                item.setString($0.absoluteString, forType: .fileURL)
                return item
            }
        case .image(let bytes?, _, _, _):
            guard let source = CGImageSourceCreateWithData(bytes as CFData, nil),
                  let type = CGImageSourceGetType(source) as String?,
                  type == "public.png" || type == "public.tiff" else { return nil }
            let item = NSPasteboardItem()
            guard item.setData(bytes, forType: type == "public.png" ? .png : .tiff) else { return nil }
            items = [item]
        default: return nil
        }
        let pasteboard = board()
        pasteboard.clearContents()
        guard pasteboard.writeObjects(items) else { return nil }
        return pasteboard.changeCount
    }

    private func board() -> NSPasteboard {
        if let pasteboard { return pasteboard }
        let pasteboard = name.map { NSPasteboard(name: .init($0)) } ?? .general
        self.pasteboard = pasteboard
        return pasteboard
    }

    private static func plainText(_ pasteboard: NSPasteboard) -> String? {
        if let text = pasteboard.string(forType: .string) { return text }
        let formats: [(NSPasteboard.PasteboardType, NSAttributedString.DocumentType)] = [(.rtf, .rtf), (.rtfd, .rtfd)]
        for (type, format) in formats {
            guard let data = pasteboard.data(forType: type), data.count <= 2 * 1024 * 1024,
                  let text = try? NSAttributedString(data: data, options: [.documentType: format], documentAttributes: nil).string,
                  !text.isEmpty else { continue }
            return text
        }
        return nil
    }

    private static func image(_ data: Data) -> ClipboardPayload {
        guard data.count <= 32 * 1024 * 1024,
              let source = CGImageSourceCreateWithData(data as CFData, [kCGImageSourceShouldCache: false] as CFDictionary),
              let properties = CGImageSourceCopyPropertiesAtIndex(source, 0, nil) as? [CFString: Any],
              let width = properties[kCGImagePropertyPixelWidth] as? Int,
              let height = properties[kCGImagePropertyPixelHeight] as? Int,
              width > 0, height > 0, width <= 100_000_000 / height else {
            return .image(bytes: nil, thumbnail: nil, width: 0, height: 0)
        }
        var thumbnail: Data?
        if let image = CGImageSourceCreateThumbnailAtIndex(source, 0, [
            kCGImageSourceCreateThumbnailFromImageAlways: true, kCGImageSourceThumbnailMaxPixelSize: 64,
            kCGImageSourceCreateThumbnailWithTransform: true, kCGImageSourceShouldCacheImmediately: false
        ] as CFDictionary) {
            let bytes = NSMutableData()
            if let destination = CGImageDestinationCreateWithData(bytes as CFMutableData, "public.png" as CFString, 1, nil) {
                CGImageDestinationAddImage(destination, image, nil)
                if CGImageDestinationFinalize(destination), bytes.length <= ClipboardHistory.maximumThumbnailBytes {
                    thumbnail = bytes as Data
                }
            }
        }
        return .image(bytes: data.count <= ClipboardHistory.maximumImageBytes ? data : nil,
                      thumbnail: thumbnail, width: width, height: height)
    }
}
